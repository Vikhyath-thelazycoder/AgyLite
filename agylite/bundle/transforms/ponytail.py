"""Generated Ponytail lite ruleset (MP3 §2.1, owner decision 2026-10-21: the lite rules are always on in L0).

Ponytail keeps its ruleset text in JavaScript (`hooks/ponytail-instructions.js` → `getPonytailInstructions(level)`), so
the bundle runs it once at build time and ships the output as `files/ponytail/RULESET-lite.md` (GENERATED provenance:
original_hash = the JS, bundled_hash = the output). The JS is untrusted input: no code generation from strings, an
empty environment (HOME is the empty working directory, so no persisted Ponytail mode is read), a timeout, and the
output must be plain text under 8 KB. Any failure fails the build; nothing is skipped silently.
"""
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

TIMEOUT = 10
MAX_BYTES = 8 * 1024
LEVEL = "lite"
CALL = "process.stdout.write(require(process.argv[1]).getPonytailInstructions(process.argv[2]))"
# Ponytail's own level commands do not exist in Agylite; the level is a config switch (mechanics only). The JS builds
# the text from skills/ponytail/SKILL.md (a declared input), or from a built-in fallback when that file is missing;
# both carry this sentence.
SWITCH = re.compile(r"Switch level: `/ponytail lite\|full\|ultra`\.")
SWITCH_AGYLITE = ("Level: lite, always on through Agylite (`config/discipline.yaml` → `ponytail_ruleset: lite|off`); "
                  "reviews: `agylite skill load ponytail/ponytail-review`.")
CONTROL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")


class GenerateError(ValueError):
    pass


def lite_ruleset(repo_dir: Path, source: str, repository: str, commit: str) -> bytes:
    node = shutil.which("node")
    if not node:
        raise GenerateError("Node.js is required to generate the Ponytail lite ruleset (files/ponytail/RULESET-lite.md) "
                            "from hooks/ponytail-instructions.js; install Node.js (the Unlazy runtime needs it too)")
    with tempfile.TemporaryDirectory() as empty:
        try:
            p = subprocess.run([node, "--disallow-code-generation-from-strings", "-e", CALL,
                                str(Path(repo_dir) / source), LEVEL],
                               cwd=empty, env={"HOME": empty}, capture_output=True, timeout=TIMEOUT)
        except subprocess.TimeoutExpired as exc:
            raise GenerateError(f"{source}: no output within {TIMEOUT} s") from exc
    if p.returncode != 0:
        tail = (p.stderr.decode("utf-8", "replace").strip().splitlines() or ["(no stderr)"])[-1]
        raise GenerateError(f"{source} exited {p.returncode}: {tail[:200]}")
    if len(p.stdout) > MAX_BYTES:
        raise GenerateError(f"{source}: {len(p.stdout)} bytes of output, over the {MAX_BYTES}-byte limit")
    try:
        text = p.stdout.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise GenerateError(f"{source}: output is not UTF-8 text") from exc
    if not text.strip() or CONTROL.search(text):
        raise GenerateError(f"{source}: output is not plain text")
    text, n = SWITCH.subn(SWITCH_AGYLITE, text)
    if n != 1:
        raise GenerateError(f"{source}: the level-switch line changed upstream (rewrite drift); update SWITCH")
    header = (f"<!-- Generated by Agylite from {repository}@{commit[:12]} {source}, level {LEVEL} "
              f"(getPonytailInstructions); regenerate with `agylite bundle build`, never edit by hand. -->\n")
    return (header + text.rstrip("\n") + "\n").encode("utf-8")


GENERATORS = {"ponytail-lite": lite_ruleset}
