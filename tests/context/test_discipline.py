"""MP3 §2.2 (owner decision 2026-10-21): the generated Ponytail lite ruleset is always on in L0, never truncated (state
lines go first), switchable with `ponytail_ruleset: lite|off` in config/discipline.yaml, and reported by doctor."""
import os
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
sys.path.insert(0, ROOT_DIR)

from tests.context.fixtures import make_bundle, make_project  # noqa: E402
from agylite.context import levels  # noqa: E402
from agylite.context.budget import load_budgets  # noqa: E402
from agylite.project.identity import detect  # noqa: E402

RULES = "\n".join(["PONYTAIL MODE ACTIVE — level: lite", "",
                   "Level: lite, always on through Agylite (`config/discipline.yaml` → `ponytail_ruleset: lite|off`).",
                   "", "You are a lazy senior developer. The best code is the code never written."]
                  + [f"- rule {i}: " + "keep it small " * 6 for i in range(30)]) + "\n"
RULESET = "<!-- Generated by Agylite from DietrichGebert/ponytail@9b58c1ffb790 hooks/ponytail-instructions.js -->\n" + RULES


class TestDiscipline(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        base = Path(self.tmp.name)
        self.home = base / "home"
        self.bundle = make_bundle(self.home)
        (self.bundle / "files" / "ponytail").mkdir(parents=True)
        (self.bundle / "files" / "ponytail" / "RULESET-lite.md").write_text(RULESET, encoding="utf-8")
        self.env = mock.patch.dict(os.environ, {"AGYLITE_HOME": str(self.home)})
        self.env.start()
        self.project = detect(make_project(base), home=self.home)
        self.budgets = load_budgets()

    def tearDown(self):
        self.env.stop()
        self.tmp.cleanup()

    def l0(self, **kw):
        return levels.bootstrap(project=self.project, session_id="s", host="cli", bundle_dir=self.bundle,
                                budgets=self.budgets, **kw)

    def test_ruleset_is_in_l0_whole_with_a_principles_pointer(self):
        l0 = self.l0()
        self.assertIn("discipline (always on):", l0["text"])
        self.assertIn(RULES.strip(), l0["text"])                      # the whole ruleset
        self.assertNotIn("<!-- Generated", l0["text"])                 # the provenance comment stays in the file
        self.assertIn("engineering/principles", l0["text"].split("discipline (always on):", 1)[1])
        self.assertNotIn("Karpathy guidelines text", l0["text"])
        self.assertLessEqual(l0["est_tokens"], self.budgets["levels"]["L0"]["max_tokens"])

    def test_state_lines_are_truncated_first_never_the_ruleset(self):
        flood = [f"line {i} " + "x" * 200 for i in range(100)]
        l0 = self.l0(state_lines=flood)
        self.assertIn(RULES.strip(), l0["text"])
        self.assertIn("truncated to the L0 budget", l0["text"])
        self.assertLessEqual(l0["est_tokens"], self.budgets["levels"]["L0"]["max_tokens"])

    def test_off_switch_and_missing_ruleset(self):
        with mock.patch.object(levels, "load_discipline", return_value={"ponytail_ruleset": "off"}):
            self.assertNotIn("discipline (always on):", self.l0()["text"])
        (self.bundle / "files" / "ponytail" / "RULESET-lite.md").unlink()
        text = self.l0()["text"]
        self.assertIn("Ponytail lite ruleset is not in this bundle", text)

    def test_config_default_is_lite_and_doctor_reports_it(self):
        from agylite.context.prompt_hook import load_discipline
        from agylite.diagnostics import doctor
        self.assertEqual(load_discipline()["ponytail_ruleset"], "lite")
        seen = []

        class R:
            def check(self, ok, good, bad):
                seen.append(good if ok else bad)
        doctor.discipline_checks(R(), Path(ROOT_DIR))
        self.assertIn("Ponytail ruleset: lite (always on in L0)", seen)


if __name__ == "__main__":
    unittest.main()
