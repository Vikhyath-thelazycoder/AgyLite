"""Convert Addy Osmani's agent-skills trigger evals into Agylite routing scenarios (MP2 T0.1).

    python tools/benchmark/addy_triggers.py <agent-skills checkout> > tests/routing/addy_trigger_scenarios.yaml

Each `trigger.positive[*]` prompt of `evals/cases/<skill>.json` expects the capability that Agylite's extraction
matrix maps `skills/<skill>/SKILL.md` to (docs/audit/evidence/extraction-matrix/addy.tsv). Skills Agylite does not
bundle are skipped and listed in a comment.
"""
import csv
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def capability_map():
    with open(ROOT / "docs/audit/evidence/extraction-matrix/addy.tsv", encoding="utf-8") as f:
        rows = csv.DictReader(f, delimiter="\t")
        return {r["path"].split("/")[1]: r["capability"] for r in rows
                if r["path"].startswith("skills/") and r["path"].endswith("/SKILL.md") and r["capability"]}


def main(checkout: Path):
    sha = subprocess.run(["git", "rev-parse", "HEAD"], cwd=checkout, capture_output=True, text=True).stdout.strip()
    caps, out, skipped = capability_map(), [], []
    for case in sorted((checkout / "evals" / "cases").glob("*.json")):
        skill = case.stem
        data = json.loads(case.read_text(encoding="utf-8"))
        if skill not in caps:
            skipped.append(skill)
            continue
        for i, p in enumerate((data.get("trigger") or {}).get("positive") or []):
            prompt = p.get("prompt") if isinstance(p, dict) else p
            out.append({"id": f"addy-{skill}-{i + 1}", "request": prompt, "stage": "existing", "expect": [caps[skill]]})
    print(f"# Generated by tools/benchmark/addy_triggers.py from addyosmani/agent-skills@{sha} (MIT, Addy Osmani).")
    print("# trigger.positive prompts of evals/cases/<skill>.json; expect = the capability Agylite maps the skill to.")
    print(f"# Skipped (not bundled): {', '.join(skipped) or 'none'}")
    print("scenarios:")
    for sc in out:
        print(f"  - id: {sc['id']}")
        print(f"    request: {json.dumps(sc['request'], ensure_ascii=False)}")
        print(f"    stage: {sc['stage']}")
        print(f"    expect: [{', '.join(sc['expect'])}]")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
